import type { CharGrid, GridStyle } from "../index";
import { gridToHtml, gridToText } from "../index";
import { DOM } from "./dom";

let current: CharGrid | null = null;

/** Display a grid in the output element (or clear it). */
export function showGrid(grid: CharGrid | null): void {
	current = grid;
	if (!grid) {
		DOM.output.textContent = "";
	} else if (grid.colors) {
		DOM.output.innerHTML = gridToHtml(grid);
	} else {
		DOM.output.textContent = gridToText(grid);
	}
}

/** The grid currently displayed, for export. */
export function outputGrid(): CharGrid | null {
	return current;
}

/** Colours the output is displayed with: fixed by Invert Glyphs. */
export function outputColors(): { background: number; foreground: number } {
	return DOM.invertGlyphsCheck.checked
		? { background: 0xffffff, foreground: 0x000000 }
		: { background: 0x000000, foreground: 0xeeeeee };
}

function hex(color: number): string {
	return `#${color.toString(16).padStart(6, "0")}`;
}

export function outputStyle(): GridStyle {
	const { background, foreground } = outputColors();
	return {
		background: hex(background),
		foreground: hex(foreground),
		fontFamily: DOM.output.style.fontFamily || "monospace",
		lineHeight: DOM.output.style.lineHeight || "normal",
	};
}
