import type { GlyphEntry } from "./distance";

/** Below this ink coverage a glyph is treated as blank and left uncoloured. */
const MIN_COVERAGE = 1e-3;

/**
 * Choose each cell's glyph colour so the cell as displayed — glyph ink over
 * the output background, including the leading between lines — averages to
 * the source cell's colour:
 *
 *     target = coverage·fg + (1 − coverage)·background
 *
 * solved per channel for `fg` and clamped to 0–255. Sparse glyphs cannot
 * always reach bright targets; those cells clamp, as they would on screen.
 *
 * Returns row-major R, G, B triplets, one per cell; blank cells get the
 * background colour.
 */
export function solveCellColors(
	cellRGB: Float32Array,
	indices: ArrayLike<number>,
	glyphs: GlyphEntry[],
	background: number,
	offset = 0,
): Uint8ClampedArray {
	const cells = cellRGB.length / 3;
	const out = new Uint8ClampedArray(cells * 3);
	for (let i = 0; i < cells; i++) {
		const alpha = glyphs[indices[offset + i]].coverage;
		for (let c = 0; c < 3; c++) {
			const target = cellRGB[i * 3 + c];
			out[i * 3 + c] =
				alpha < MIN_COVERAGE
					? background
					: background + (target - background) / alpha;
		}
	}
	return out;
}
